"""Fish completion script synthesis."""

from treefort.cli_manifest import CommandSpec, ParamSpec
from treefort.shells._common import (
    CMD_PLACEHOLDER,
    GLOBAL_FLAGS,
    HELPER_BODIES,
    PROVIDER_HELPERS,
    PROVIDER_PREFIXES,
    CandidateSource,
    candidate_source,
    command_words,
    flag_params,
    helper_names,
    positional_params,
    sorted_commands,
)


def wrapper(cmd: str = CMD_PLACEHOLDER) -> str:
    """Render the fish function that applies the ``TREEFORT_CD_FILE`` directive."""
    return f"""\
function {cmd}
    set -l cd_file (mktemp)
    TREEFORT_CD_FILE=$cd_file command {cmd} $argv
    set -l status $status
    if test -s $cd_file
        cd -- (cat $cd_file)
    end
    rm -f -- $cd_file
    return $status
end"""


def completion_script(
    commands: dict[str, CommandSpec], alias_map: dict[str, str], cmd: str = CMD_PLACEHOLDER
) -> str:
    """Render a self-contained fish completion script for the given commands."""
    blocks = [
        f"# fish completion for {cmd}",
        "# Generated by treefort. Do not edit.",
        _helpers(commands),
        _root_rules(commands, alias_map, cmd),
        *(_command_rules(spec, cmd) for spec in sorted_commands(commands)),
    ]
    return "\n\n".join(block for block in blocks if block) + "\n"


def _helpers(commands: dict[str, CommandSpec]) -> str:
    return "\n\n".join(
        f"function __treefort_{name}\n    {HELPER_BODIES[name]}\nend"
        for name in helper_names(commands)
    )


def _root_rules(commands: dict[str, CommandSpec], alias_map: dict[str, str], cmd: str) -> str:
    rules = [f"complete -c {cmd} -f"]
    for word in command_words(commands, alias_map):
        spec = commands.get(alias_map.get(word, word))
        description = _quote(spec.summary if spec is not None else "")
        rules.append(
            f'complete -c {cmd} -n "__fish_use_subcommand" -a {_quote(word)} -d {description}'
        )
    rules.extend(_global_flag_rules(cmd, "__fish_use_subcommand"))
    return "\n".join(rules)


def _global_flag_rules(cmd: str, condition: str) -> list[str]:
    rules = []
    for flag in GLOBAL_FLAGS:
        if flag.startswith("--"):
            option = f"-l {flag[2:]}"
            description = _global_flag_description(flag)
        else:
            option = f"-s {flag[1:]}"
            description = _global_flag_description(flag)
        rules.append(f"complete -c {cmd} -n {_quote(condition)} {option} -d {_quote(description)}")
    return rules


def _command_rules(spec: CommandSpec, cmd: str) -> str:
    condition = f"__fish_seen_subcommand_from {' '.join([spec.name, *spec.aliases])}"
    rules = _global_flag_rules(cmd, condition)
    for param in flag_params(spec):
        rules.append(_flag_rule(param, cmd, _quote(condition)))
    for index, param in enumerate(positional_params(spec)):
        rule = _positional_rule(param, index, cmd, condition)
        if rule:
            rules.append(rule)
    return "\n".join(rules)


def _flag_rule(param: ParamSpec, cmd: str, condition: str) -> str:
    description = _quote(param.description)
    short = f"-s {param.short.lstrip('-')} " if param.short is not None else ""
    name = param.name.replace("_", "-")

    if param.value_type == "bool":
        rules = [f"complete -c {cmd} -n {condition} -l {name} {short}-d {description}"]
        if param.default is True:
            rules.append(f"complete -c {cmd} -n {condition} -l no-{name} -d {description}")
        return "\n".join(rules)

    source = candidate_source(param)
    if source is None:
        return f"complete -c {cmd} -n {condition} -l {name} {short}-x -d {description}"
    return (
        f"complete -c {cmd} -n {condition} -l {name} {short}-x "
        f"-a {_fish_candidates(source)} -d {description}"
    )


def _positional_rule(param: ParamSpec, index: int, cmd: str, condition: str) -> str:
    source = candidate_source(param)
    if source is None:
        return ""
    # Fish has no positional index, so the argument count stands in for one
    positioned = f"{condition}; and test (count (commandline -opc)) -eq {index + 2}"
    return (
        f"complete -c {cmd} -n {_quote(positioned)} -a {_fish_candidates(source)} "
        f"-d {_quote(param.description)}"
    )


def _fish_candidates(source: CandidateSource) -> str:
    if source.kind == "words":
        return _quote(" ".join(source.words))
    parts = list(PROVIDER_PREFIXES.get(source.provider, ()))
    parts.append(f"(__treefort_{PROVIDER_HELPERS[source.provider]})")
    # Double quotes still run the command substitution, and keep the whole list in one argument
    return '"' + " ".join(parts) + '"'


def _global_flag_description(flag: str) -> str:
    if flag in ("-h", "--help"):
        return "Show this help message and exit"
    return "Enable verbose debug logging"


def _quote(text: str) -> str:
    """Quote text for fish, collapsing whitespace and escaping quotes."""
    collapsed = " ".join(text.split())
    return "'" + collapsed.replace("\\", "\\\\").replace("'", "\\'") + "'"
