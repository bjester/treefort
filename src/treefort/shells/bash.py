"""Bash completion script synthesis."""

from treefort.cli_manifest import CommandSpec
from treefort.shells._common import (
    CMD_PLACEHOLDER,
    GLOBAL_FLAGS,
    HELPER_BODIES,
    PROVIDER_HELPERS,
    PROVIDER_PREFIXES,
    CandidateSource,
    all_flag_spellings,
    candidate_source,
    command_words,
    flag_params,
    helper_names,
    positional_params,
    sorted_commands,
    value_flag_spellings,
)

# Counts the positional arguments typed after the command. A value flag's argument belongs to
# the flag, so the token following one of those spellings is skipped.
POSITIONAL_COUNT = """\
_treefort_positional_count() {
    local start=$1
    shift
    local -a value_flags=("$@")
    local i count=0 expect=0 word flag
    for (( i=start+1; i < COMP_CWORD; i++ )); do
        word="${COMP_WORDS[i]}"
        if (( expect )); then
            expect=0
            continue
        fi
        case "$word" in
            -*=*) continue ;;
            -*)
                for flag in "${value_flags[@]}"; do
                    if [ "$word" = "$flag" ]; then
                        expect=1
                        break
                    fi
                done
                continue
                ;;
        esac
        count=$(( count + 1 ))
    done
    printf '%s' "$count"
}"""


def wrapper(cmd: str = CMD_PLACEHOLDER) -> str:
    """Render the bash function that applies the ``TREEFORT_CD_FILE`` directive."""
    return f"""\
{cmd}() {{
    local cd_file status
    cd_file="$(mktemp)"
    TREEFORT_CD_FILE="$cd_file" command {cmd} "$@"
    status=$?
    if [ -s "$cd_file" ]; then
        cd -- "$(<"$cd_file")" || true
    fi
    rm -f -- "$cd_file"
    return $status
}}"""


def completion_script(
    commands: dict[str, CommandSpec], alias_map: dict[str, str], cmd: str = CMD_PLACEHOLDER
) -> str:
    """Render a self-contained bash completion script for the given commands."""
    blocks = [
        f"# bash completion for {cmd}",
        "# Generated by treefort. Do not edit.",
        POSITIONAL_COUNT,
        _helpers(commands),
        _dispatcher(commands, alias_map),
        *(_command_function(spec) for spec in sorted_commands(commands)),
        f"complete -F _treefort_complete {cmd}",
    ]
    return "\n\n".join(block for block in blocks if block) + "\n"


def _helpers(commands: dict[str, CommandSpec]) -> str:
    return "\n\n".join(
        f"_treefort_{name}() {{\n    {HELPER_BODIES[name]}\n}}" for name in helper_names(commands)
    )


def _dispatcher(commands: dict[str, CommandSpec], alias_map: dict[str, str]) -> str:
    root_words = " ".join(command_words(commands, alias_map) + list(GLOBAL_FLAGS))
    cases = []
    for spec in sorted_commands(commands):
        labels = "|".join([spec.name, *spec.aliases])
        cases.append(
            f"        {labels})\n"
            f'            _treefort_complete_{_function_suffix(spec.name)} "$prev" "$cur" "$i"\n'
            "            return 0\n"
            "            ;;"
        )
    return f"""\
_treefort_complete() {{
    local cur prev word command i
    COMPREPLY=()
    cur="${{COMP_WORDS[COMP_CWORD]}}"
    prev="${{COMP_WORDS[COMP_CWORD-1]}}"
    command=""
    for (( i=1; i < COMP_CWORD; i++ )); do
        word="${{COMP_WORDS[i]}}"
        case "$word" in
            -*) continue ;;
        esac
        command="$word"
        break
    done

    case "$command" in
        ""|help)
            COMPREPLY=( $(compgen -W "{root_words}" -- "$cur") )
            return 0
            ;;
{chr(10).join(cases)}
    esac
}}"""


def _command_function(spec: CommandSpec) -> str:
    # Each spelling is its own word so the helper can match it against a typed token
    value_flags = " ".join(value_flag_spellings(spec))
    count_args = f" {value_flags}" if value_flags else ""
    return f"""\
_treefort_complete_{_function_suffix(spec.name)}() {{
    local prev="$1" cur="$2" position
    position=$(_treefort_positional_count "$3"{count_args})
{_command_body(spec)}
}}"""


def _command_body(spec: CommandSpec) -> str:
    parts = [
        part
        for part in (_value_cases(spec), _inline_value_cases(spec), _completion_case(spec))
        if part
    ]
    return "\n".join(parts)


def _value_cases(spec: CommandSpec) -> str:
    cases = []
    for param in flag_params(spec):
        if param.value_type == "bool":
            continue
        spellings = [f"--{param.name.replace('_', '-')}"]
        if param.short is not None:
            spellings.append(param.short)
        source = candidate_source(param)
        if source is None:
            # A value flag without candidates still ends completion, so the value is never
            # offered the command's positional candidates
            cases.append(f"        {'|'.join(spellings)})\n            return 0\n            ;;")
            continue
        cases.append(
            f"        {'|'.join(spellings)})\n"
            f'            COMPREPLY=( $(compgen -W "{_word_expression(source)}" -- "$cur") )\n'
            "            return 0\n"
            "            ;;"
        )
    if not cases:
        return ""
    return '    case "$prev" in\n' + "\n".join(cases) + "\n    esac"


def _inline_value_cases(spec: CommandSpec) -> str:
    cases = []
    for param in flag_params(spec):
        source = candidate_source(param)
        if source is None or param.value_type == "bool":
            continue
        spellings = [f"--{param.name.replace('_', '-')}"]
        if param.short is not None:
            spellings.append(param.short)
        for spelling in spellings:
            cases.append(
                f"        {spelling}=*)\n"
                f'            COMPREPLY=( $(compgen -W "{_word_expression(source)}"'
                ' -- "${cur#*=}") )\n'
                f'            COMPREPLY=( "${{COMPREPLY[@]/#/{spelling}=}}" )\n'
                "            return 0\n"
                "            ;;"
            )
    if not cases:
        return ""
    return '    case "$cur" in\n' + "\n".join(cases) + "\n    esac"


def _completion_case(spec: CommandSpec) -> str:
    flag_words = " ".join(all_flag_spellings(spec) + list(GLOBAL_FLAGS))
    flags = (
        '    case "$cur" in\n'
        f'        -*)\n            COMPREPLY=( $(compgen -W "{flag_words}" -- "$cur") )\n'
        "            return 0\n"
        "            ;;\n"
        "    esac"
    )
    positional = _positional_case(spec)
    return "\n".join(part for part in (flags, positional) if part)


def _positional_case(spec: CommandSpec) -> str:
    params = positional_params(spec)
    branches = []
    for index, param in enumerate(params):
        source = candidate_source(param)
        if param.kind != "variadic_positional" and source is None:
            continue
        label = "*" if param.kind == "variadic_positional" else str(index)
        words = _word_expression(source) if source is not None else ""
        branches.append(
            f"        {label})\n"
            f'            COMPREPLY=( $(compgen -W "{words}" -- "$cur") )\n'
            "            ;;"
        )
    if not branches:
        return ""
    return '    case "$position" in\n' + "\n".join(branches) + "\n    esac"


def _word_expression(source: CandidateSource) -> str:
    if source.kind == "words":
        return " ".join(source.words)
    prefixes = " ".join(PROVIDER_PREFIXES.get(source.provider, ()))
    helper = f"$(_treefort_{PROVIDER_HELPERS[source.provider]})"
    return f"{prefixes} {helper}".strip()


def _function_suffix(name: str) -> str:
    return name.replace("-", "_")
